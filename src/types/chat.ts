// src/types/chat.ts

// Added 'system' to match the sendSystemMessage function in your service
export type MessageType = 'text' | 'image' | 'video' | 'audio' | 'voice' | 'document' | 'location' | 'system';

export interface BaseMessage {
  id?: string; // Generated by Firestore snapshot
  fromUid: string;
  fromName: string;
  fromPhotoUrl: string | null;
  createdAt: any; // Firestore Timestamp
  deletedAt: any | null;
  type: MessageType;
  text: string;

  // Legacy fields (kept for backwards compatibility as defined in your service)
  imageUrl: string | null;
  voiceUrl: string | null;
  voiceDurationMs: number | null;

  // Universal media fields
  mediaUrl: string | null;
  mediaMime: string | null;
  mediaSize: number | null;
  mediaName: string | null;
  mediaDurationMs: number | null;
  thumbnailUrl: string | null;

  // Location fields
  latitude: number | null;
  longitude: number | null;
  address: string | null;
  isLive: boolean | null;
}

export interface TextMessage extends BaseMessage {
  type: 'text';
}

export interface MediaMessage extends BaseMessage {
  type: 'image' | 'video' | 'audio' | 'document';
  mediaUrl: string; // Guaranteed to be present for media
}

export interface VoiceMessage extends BaseMessage {
  type: 'voice';
  mediaUrl: string; 
  mediaDurationMs: number;
}

export interface LocationMessage extends BaseMessage {
  type: 'location';
  latitude: number;
  longitude: number;
}

export interface SystemMessage extends BaseMessage {
  type: 'system';
}

export type ChatMessage = TextMessage | MediaMessage | VoiceMessage | LocationMessage | SystemMessage;